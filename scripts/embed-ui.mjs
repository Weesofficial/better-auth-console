// Inlines the Vite build into one HTML string and records the CSP hash of each
// inline script and style, so the page can run under a CSP without 'unsafe-inline'.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const dist = new URL("../dist-ui/", import.meta.url);
let html = readFileSync(new URL("index.html", dist), "utf8");
const scripts = [];
const styles = [];
const hash = (text) => `sha256-${createHash("sha256").update(text, "utf8").digest("base64")}`;
const read = (src) => readFileSync(new URL(src.replace(/^\//, ""), dist), "utf8");

html = html.replace(/<script type="module" crossorigin src="([^"]+)"><\/script>/g, (_, src) => {
  const code = read(src);
  if (/<\/script/i.test(code)) throw new Error(`embed-ui: ${src} contains </script`);
  scripts.push(hash(code));
  return `<script type="module">${code}</script>`;
});
html = html.replace(/<link rel="stylesheet" crossorigin href="([^"]+)">/g, (_, href) => {
  const css = read(href);
  if (/<\/style/i.test(css)) throw new Error(`embed-ui: ${href} contains </style`);
  styles.push(hash(css));
  return `<style>${css}</style>`;
});
if (!scripts.length || !styles.length || /\b(src|href)="\/assets\//.test(html)) {
  throw new Error("embed-ui: the built HTML didn't have the expected script and stylesheet tags");
}

writeFileSync(
  new URL("../src/ui.generated.ts", import.meta.url),
  `// Generated by scripts/embed-ui.mjs. Do not edit.\n` +
    `export const HTML = ${JSON.stringify(html)};\n` +
    `export const SCRIPT_HASHES = ${JSON.stringify(scripts)};\n` +
    `export const STYLE_HASHES = ${JSON.stringify(styles)};\n`,
);
console.log(`embed-ui: ${(html.length / 1024).toFixed(1)} KB`);
